import type { ProviderMessage } from '../providers/provider-types.js';
import type { ContextMessage } from './context-message.js';

/** The summariser's fixed instructions; part of the library's behaviour, so changing it is a library version change. */
export const SUMMARISER_PROMPT = [
  'You compress the earlier part of an agent\'s working session into one summary that replaces it.',
  'Write plain text under these headings, in this order: Goal, Decisions, Facts, Open items, Tool outcomes.',
  'Keep every fact the agent may still need: file paths, identifiers, numbers, names, errors and results, copied exactly.',
  'Keep negations and constraints exactly as stated. Mention result_original handles (such as H3) that results were stored under.',
  'Merge the previous summary, if any, into the new one: one summary, nothing dropped that is still relevant.',
  'Use at most 250 words. Do not address the user and do not continue the task.',
].join('\n');

/** First line of the stored summary message. */
export const SUMMARY_HEADING = '# Summary of earlier work (generated by the runtime, not written by the user)';

function renderMessage(context: ContextMessage): string {
  const { message: { role, text = '', toolCalls = [], toolCallId } } = context;
  if (role === 'tool') return `[result of call ${toolCallId ?? '?'}]\n${text}`;
  const calls = toolCalls.map(({ id, name, args }) => `[call ${id}] ${name} ${JSON.stringify(args) ?? ''}`);
  return [`[${role}]${text === '' ? '' : `\n${text}`}`, ...calls].join('\n');
}

export interface SummaryRequestParams {
  /** The current summary's text, merged into the new one. */
  previousSummary?: string;
  /** The messages being summarised, in stored order. */
  messages: readonly ContextMessage[];
}

/** The summariser's messages: the fixed prompt, then the previous summary and the transcript to compress. */
export function summaryRequestMessages(params: SummaryRequestParams): ProviderMessage[] {
  const { previousSummary, messages } = params;
  const previous = previousSummary == null ? '' : `## Previous summary\n${previousSummary}\n\n`;
  const transcript = messages.map(renderMessage).join('\n\n');
  return [{ role: 'system', text: SUMMARISER_PROMPT }, { role: 'user', text: `${previous}## Conversation to summarise\n${transcript}` }];
}

/** The stored summary message's text. */
export function summaryMessageText(summary: string): string {
  return `${SUMMARY_HEADING}\n${summary.trim()}`;
}
