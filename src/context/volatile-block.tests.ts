import { describe, expect, it } from 'vitest';
import { buildVolatileBlock, parseVolatileOptions } from './volatile-block.js';
import type { VolatileOptions, VolatileSection } from './volatile-block.js';

/** 2026-10-20 14:37:42.123 UTC. */
const AT = Date.UTC(2026, 9, 20, 14, 37, 42, 123);
const PROGRESS = { turn: 2, maxTurns: 25, toolCalls: 3, maxToolCalls: 100 };

interface BlockParams {
  extras?: VolatileSection[];
  now?: number;
}

function block(options: VolatileOptions = {}, params: BlockParams = {}): string | undefined {
  const { extras = [], now = AT } = params;
  return buildVolatileBlock({ clock: { now: () => now }, options, progress: PROGRESS, extras });
}

describe('buildVolatileBlock', () => {
  it('renders date/time, progress and extras in a fixed order under # Current state', () => {
    expect(block({}, { extras: [{ title: 'Plan status', body: '- p1: done' }, { title: 'Todo status', body: '- t1: pending' }] })).toBe([
      '# Current state (generated by the runtime, not written by the user)',
      'Date and time: 2026-10-20 14:37 (UTC)',
      'Progress: turn 2 of 25; 3 of 100 tool calls used',
      '',
      '## Plan status',
      '- p1: done',
      '',
      '## Todo status',
      '- t1: pending',
    ].join('\n'));
  });

  it.each([
    ['minute', '2026-10-20 14:37'],
    ['hour', '2026-10-20 14:00'],
    ['day', '2026-10-20'],
  ] as const)('rounds the time down to the %s', (granularity, shown) => {
    expect(block({ dateTime: { granularity } })).toContain(`Date and time: ${shown} (UTC)`);
  });

  it('is identical for any instant within the same granularity', () => {
    expect(block({}, { now: AT + 10_000 })).toBe(block());
    expect(block({ dateTime: { granularity: 'hour' } }, { now: AT + 20 * 60_000 })).toBe(block({ dateTime: { granularity: 'hour' } }));
  });

  it('renders the time in the configured timezone and names the locale', () => {
    const rendered = block({ timezone: 'Asia/Tokyo', locale: 'ja-JP', dateTime: { granularity: 'day' } });
    expect(rendered).toContain('Date and time: 2026-10-20 (Asia/Tokyo)');
    expect(rendered).toContain('Locale: ja-JP');
    expect(block({ timezone: 'Asia/Tokyo' }, { now: Date.UTC(2026, 9, 20, 20, 0) })).toContain('2026-10-21 05:00 (Asia/Tokyo)');
  });

  it('leaves the date out with dateTime: false and is undefined when nothing remains', () => {
    expect(block({ dateTime: false })).toBe('# Current state (generated by the runtime, not written by the user)\nProgress: turn 2 of 25; 3 of 100 tool calls used');
    expect(block({ dateTime: false, progress: false })).toBeUndefined();
    expect(block({ dateTime: false, progress: false }, { extras: [{ title: 'Plan status', body: 'x' }] })).toBe('# Current state (generated by the runtime, not written by the user)\n\n## Plan status\nx');
  });
});

describe('parseVolatileOptions', () => {
  it('accepts valid options and rejects unknown keys, granularities and timezones', () => {
    expect(parseVolatileOptions(undefined)).toEqual({});
    expect(parseVolatileOptions({ dateTime: { granularity: 'hour' }, timezone: 'Europe/London', locale: 'en-GB', warnOnPrefixChange: true })).toMatchObject({ timezone: 'Europe/London' });
    expect(() => parseVolatileOptions({ dateTime: { granularity: 'second' } } as unknown as VolatileOptions)).toThrow(expect.objectContaining({ code: 'invalid_definition' }));
    expect(() => parseVolatileOptions({ timezone: 'Mars/Olympus' })).toThrow(/timezone 'Mars\/Olympus'/);
    expect(() => parseVolatileOptions({ extra: 1 } as unknown as VolatileOptions)).toThrow(/extra/);
  });
});
